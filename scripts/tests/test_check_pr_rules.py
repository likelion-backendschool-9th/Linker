import importlib.util
import pathlib
import unittest

SPEC = importlib.util.spec_from_file_location(
    "check_pr_rules", pathlib.Path(__file__).resolve().parents[1] / "check_pr_rules.py"
)
rules = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(rules)


class TitleTest(unittest.TestCase):
    def test_valid_titles(self):
        self.assertEqual(rules.check_title("chore: 라벨 스크립트 정리"), ("chore", []))
        self.assertEqual(rules.check_title("feat: 로그인 구현 (#12)")[0], "feat")

    def test_rejects_wrong_type_and_format(self):
        for title in ("refactor: 구조 정리", "feature: 로그인", "docs:문서", "로그인 구현", "fix"):
            self.assertTrue(rules.check_title(title)[1], title)

    def test_rejects_non_korean_description(self):
        self.assertTrue(rules.check_title("fix: login error")[1])


class BranchTest(unittest.TestCase):
    def test_valid_branch_matches_title_type(self):
        self.assertEqual(rules.check_branch("chore/git-rule-automation", "dev", "chore"), [])

    def test_rejects_type_mismatch_and_bad_names(self):
        self.assertTrue(rules.check_branch("feat/login", "dev", "chore"))
        for name in ("feature/login", "refactor/x", "chore/Upper", "chore/a_b", "login"):
            self.assertTrue(rules.check_branch(name, "dev", None), name)

    def test_dev_to_main_is_exempt(self):
        self.assertEqual(rules.check_branch("dev", "main", "chore"), [])
        self.assertTrue(rules.check_branch("dev", "dev", "chore"))


class AgentMarkTest(unittest.TestCase):
    def test_detects_known_marks(self):
        samples = (
            "Co-Authored-By: Claude Sonnet 5.5 <noreply@anthropic.com>",
            "co-authored-by: Cursor <cursoragent@cursor.com>",
            "🤖 Generated with [Claude Code](https://claude.com/claude-code)",
            "Made-with: Cursor",
            "Generated by Copilot",
        )
        for sample in samples:
            self.assertTrue(rules.find_agent_marks("본문", sample), sample)

    def test_allows_human_coauthors_and_plain_text(self):
        for sample in ("Co-authored-by: Hong Gildong <hong@example.com>", "채팅 모듈 정리\n\n- 클로드 문서 갱신", "claude 규칙 문서 수정"):
            self.assertEqual(rules.find_agent_marks("본문", sample), [], sample)


class RunTest(unittest.TestCase):
    def test_full_pass_and_fail(self):
        ok = rules.run("chore: 규칙 검사 추가", "본문", "chore/git-rule-automation", "dev", ["chore: 추가"])
        self.assertEqual(ok, [])
        bad = rules.run("chore: 규칙 검사 추가", "본문", "chore/git-rule-automation", "dev", ["x\n\nCo-Authored-By: Claude <a@b>"])
        self.assertEqual(len(bad), 1)


if __name__ == "__main__":
    unittest.main()
