-- Existing ERD tables only. Never execute against a shared DB without the team's migration review.
CREATE TABLE issues (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id bigint NOT NULL REFERENCES teams(id),
    repo_id bigint NOT NULL REFERENCES github_repos(id),
    github_issue_id bigint NOT NULL UNIQUE,
    github_node_id varchar NOT NULL,
    number integer NOT NULL CHECK (number > 0),
    title varchar NOT NULL,
    state varchar(16) NOT NULL CHECK (state IN ('OPEN', 'CLOSED')),
    board_status varchar(16) NOT NULL CHECK (board_status IN ('TODO','IN_PROGRESS','BLOCKED','DONE','OTHER','NONE')),
    project_item_id varchar,
    start_date date,
    due_date date,
    author_user_id bigint REFERENCES users(id),
    author_login varchar,
    created_via_linker boolean NOT NULL DEFAULT false,
    sync_status varchar(16) NOT NULL CHECK (sync_status IN ('SYNCED','PENDING','FAILED')),
    parent_issue_id bigint REFERENCES issues(id),
    sub_issues_total integer NOT NULL DEFAULT 0 CHECK (sub_issues_total >= 0),
    sub_issues_done integer NOT NULL DEFAULT 0 CHECK (sub_issues_done >= 0),
    html_url varchar,
    github_updated_at timestamptz NOT NULL,
    closed_at timestamptz,
    deleted_at timestamptz,
    synced_at timestamptz,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    UNIQUE (repo_id, number),
    CHECK (start_date IS NULL OR due_date IS NULL OR start_date <= due_date)
);

CREATE TABLE issue_assignees (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    issue_id bigint NOT NULL REFERENCES issues(id) ON DELETE CASCADE,
    github_user_id bigint NOT NULL,
    github_login varchar NOT NULL,
    user_id bigint REFERENCES users(id),
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    UNIQUE (issue_id, github_user_id)
);

CREATE TABLE issue_labels (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    issue_id bigint NOT NULL REFERENCES issues(id) ON DELETE CASCADE,
    name varchar NOT NULL,
    color varchar NOT NULL,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    UNIQUE (issue_id, name)
);


-- Existing ERD table. Referenced to avoid marking unfinished user-write jobs SYNCED.
CREATE TABLE issue_sync_jobs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    issue_id bigint NOT NULL REFERENCES issues(id) ON DELETE CASCADE,
    step varchar NOT NULL CHECK (step IN ('ADD_TO_PROJECT','SET_START','SET_DUE','SET_STATUS','CLOSE','REOPEN')),
    payload jsonb,
    status varchar NOT NULL CHECK (status IN ('PENDING','RUNNING','DONE','FAILED')),
    attempts integer NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    next_retry_at timestamptz,
    last_error text,
    requested_by bigint NOT NULL REFERENCES users(id),
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL
);
