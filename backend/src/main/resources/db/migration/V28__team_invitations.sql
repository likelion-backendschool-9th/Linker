-- Existing ERD invitation tables; V28 agreed for page 09/10 integration.
CREATE TABLE team_invite_links (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id bigint NOT NULL REFERENCES teams(id),
    token_hash varchar(64) NOT NULL UNIQUE,
    created_by bigint NOT NULL REFERENCES users(id),
    expires_at timestamptz NOT NULL, revoked_at timestamptz,
    created_at timestamptz NOT NULL, updated_at timestamptz NOT NULL
);
CREATE INDEX team_invite_links_team_idx ON team_invite_links(team_id, expires_at);
CREATE TABLE github_org_invitations (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id bigint NOT NULL REFERENCES teams(id),
    inviter_id bigint NOT NULL REFERENCES users(id),
    invitee_user_id bigint NOT NULL REFERENCES users(id),
    invitee_login varchar(255) NOT NULL,
    github_invitation_id bigint,
    status varchar(16) NOT NULL CHECK(status IN ('PENDING','ACCEPTED','FAILED','EXPIRED')),
    reminded_at timestamptz,
    created_at timestamptz NOT NULL, updated_at timestamptz NOT NULL
);
