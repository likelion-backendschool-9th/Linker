-- Included profile data: old logins, contribution days, interest categories,
-- recruiter views, and one job ad per recruiter.

CREATE TABLE username_redirects (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    old_username varchar(39) NOT NULL,
    user_id bigint NOT NULL,
    expires_at timestamptz NOT NULL,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    CONSTRAINT username_redirects_user_id_fk FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT username_redirects_old_username_uk UNIQUE (old_username)
);

CREATE TABLE contribution_days (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL,
    day date NOT NULL,
    contribution_count integer NOT NULL,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    CONSTRAINT contribution_days_user_id_fk FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT contribution_days_user_day_uk UNIQUE (user_id, day),
    CONSTRAINT contribution_days_count_chk CHECK (contribution_count >= 0)
);

CREATE TABLE user_job_categories (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL,
    job_category varchar(32) NOT NULL,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    CONSTRAINT user_job_categories_user_id_fk FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT user_job_categories_user_category_uk UNIQUE (user_id, job_category),
    CONSTRAINT user_job_categories_category_chk CHECK (job_category IN (
        'FRONTEND', 'BACKEND', 'FULLSTACK', 'MOBILE', 'DATA_AI', 'DEVOPS', 'GAME', 'EMBEDDED', 'SECURITY', 'QA'
    ))
);

CREATE TABLE profile_visits (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    profile_user_id bigint NOT NULL,
    visitor_id bigint NOT NULL,
    visit_date date NOT NULL,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    CONSTRAINT profile_visits_profile_user_id_fk FOREIGN KEY (profile_user_id) REFERENCES users (id),
    CONSTRAINT profile_visits_visitor_id_fk FOREIGN KEY (visitor_id) REFERENCES users (id),
    CONSTRAINT profile_visits_once_per_day_uk UNIQUE (profile_user_id, visitor_id, visit_date)
);

CREATE TABLE recruiter_ads (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recruiter_id bigint NOT NULL,
    job_category varchar(32) NOT NULL,
    title varchar(40) NOT NULL,
    url varchar(2048) NOT NULL,
    url_host varchar(255) NOT NULL,
    closes_on date NOT NULL,
    status varchar(16) NOT NULL,
    ended_reason varchar(32),
    hidden_at timestamptz,
    deleted_at timestamptz,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    CONSTRAINT recruiter_ads_recruiter_id_fk FOREIGN KEY (recruiter_id) REFERENCES users (id),
    CONSTRAINT recruiter_ads_recruiter_id_uk UNIQUE (recruiter_id),
    CONSTRAINT recruiter_ads_category_chk CHECK (job_category IN (
        'FRONTEND', 'BACKEND', 'FULLSTACK', 'MOBILE', 'DATA_AI', 'DEVOPS', 'GAME', 'EMBEDDED', 'SECURITY', 'QA'
    )),
    CONSTRAINT recruiter_ads_status_chk CHECK (status IN ('ACTIVE', 'PAUSED', 'ENDED', 'HIDDEN')),
    CONSTRAINT recruiter_ads_ended_reason_chk CHECK (ended_reason IS NULL OR ended_reason IN ('CLOSED', 'PLAN_EXPIRED'))
);
