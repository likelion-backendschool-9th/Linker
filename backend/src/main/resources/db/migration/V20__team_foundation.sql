-- B team foundation. Existing ERD tables, promoted from the page 07/08 preparation SQL.
-- V1-V19 stay unchanged. github_repos is owned by V12; webhook installation_id stays external.
-- B reserves V20 only. C issue migrations follow this version.
-- Fail on conflicting/pre-applied tables or orphaned chat team IDs; never discard existing data.

CREATE TABLE github_installations (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    github_installation_id bigint NOT NULL UNIQUE,
    account_id bigint NOT NULL,
    account_login varchar(255) NOT NULL,
    account_type varchar(32) NOT NULL,
    repository_selection varchar(16) NOT NULL,
    installed_by bigint NOT NULL REFERENCES users(id),
    suspended_at timestamptz, removed_at timestamptz,
    created_at timestamptz NOT NULL, updated_at timestamptz NOT NULL
);
CREATE TABLE teams (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    installation_id bigint NOT NULL REFERENCES github_installations(id),
    github_org_id bigint NOT NULL UNIQUE,
    github_org_login varchar(255) NOT NULL,
    name varchar(255) NOT NULL, description text, avatar_url varchar(2048),
    status varchar(16) NOT NULL CHECK (status IN ('ACTIVE','COMPLETED','READ_ONLY','ARCHIVED','DELETED')),
    org_base_permission varchar(32),
    created_by bigint NOT NULL REFERENCES users(id),
    read_only_since timestamptz, archived_at timestamptz, delete_scheduled_at timestamptz,
    ai_summary_enabled boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL, updated_at timestamptz NOT NULL
);
CREATE TABLE team_members (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id bigint NOT NULL REFERENCES teams(id), user_id bigint NOT NULL REFERENCES users(id),
    role varchar(16) NOT NULL CHECK (role IN ('OWNER','ADMIN','MEMBER')),
    github_org_state varchar(16) NOT NULL CHECK (github_org_state IN ('NOT_MEMBER','INVITED','MEMBER')),
    joined_at timestamptz NOT NULL, left_at timestamptz,
    leave_type varchar(16) CHECK (leave_type IN ('LEFT','KICKED','ORG_REMOVED','TEAM_DELETED')),
    created_at timestamptz NOT NULL, updated_at timestamptz NOT NULL
);
CREATE UNIQUE INDEX team_members_current_uk
    ON team_members(team_id, user_id) WHERE left_at IS NULL;
CREATE INDEX team_members_user_current_idx
    ON team_members(user_id, joined_at DESC) WHERE left_at IS NULL;

ALTER TABLE chat_rooms ADD CONSTRAINT chat_rooms_team_id_fk
    FOREIGN KEY (team_id) REFERENCES teams(id);

CREATE TABLE team_repos (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id bigint NOT NULL REFERENCES teams(id),
    repo_id bigint NOT NULL REFERENCES github_repos(id),
    connected_by bigint NOT NULL REFERENCES users(id),
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    CONSTRAINT team_repos_team_repo_uk UNIQUE (team_id, repo_id)
);
CREATE INDEX team_repos_repo_idx ON team_repos(repo_id);

CREATE TABLE team_project_boards (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id bigint NOT NULL UNIQUE REFERENCES teams(id),
    github_project_node_id varchar(255) NOT NULL,
    project_number integer NOT NULL,
    title varchar(255) NOT NULL,
    created_by_linker boolean NOT NULL,
    status_field_id varchar(255) NOT NULL,
    start_date_field_id varchar(255) NOT NULL,
    due_date_field_id varchar(255) NOT NULL,
    connected_by bigint NOT NULL REFERENCES users(id),
    created_at timestamptz NOT NULL, updated_at timestamptz NOT NULL
);
CREATE TABLE board_status_mappings (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    board_id bigint NOT NULL REFERENCES team_project_boards(id),
    github_option_id varchar(255) NOT NULL,
    github_option_name varchar(255) NOT NULL,
    linker_status varchar(32) NOT NULL CHECK (linker_status IN ('TODO','IN_PROGRESS','BLOCKED','DONE','OTHER')),
    created_at timestamptz NOT NULL, updated_at timestamptz NOT NULL,
    UNIQUE(board_id,github_option_id)
);
CREATE TABLE pull_requests (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id bigint NOT NULL REFERENCES teams(id), repo_id bigint NOT NULL REFERENCES github_repos(id),
    github_pr_id bigint NOT NULL UNIQUE, number integer NOT NULL,
    title text NOT NULL, state varchar(16) NOT NULL CHECK (state IN ('OPEN','CLOSED','MERGED')),
    draft boolean NOT NULL, author_login varchar(255), html_url varchar(2048),
    merged_at timestamptz, closed_at timestamptz, github_updated_at timestamptz NOT NULL,
    created_at timestamptz NOT NULL, updated_at timestamptz NOT NULL,
    UNIQUE(repo_id,number)
);
