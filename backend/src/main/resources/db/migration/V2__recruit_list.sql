-- teams is page 08; recruit_posts.team_id is stored without FK until that table exists.

CREATE TABLE recruit_posts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    author_id bigint NOT NULL,
    team_id bigint,
    title varchar(40) NOT NULL,
    description varchar(1000) NOT NULL,
    work_mode varchar(16) NOT NULL,
    region varchar(100),
    goal varchar(16),
    expected_period varchar(40),
    deadline date NOT NULL,
    status varchar(16) NOT NULL,
    visibility varchar(16) NOT NULL,
    sort_at timestamptz NOT NULL,
    closed_at timestamptz,
    deleted_at timestamptz,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    CONSTRAINT recruit_posts_author_id_fk FOREIGN KEY (author_id) REFERENCES users (id),
    CONSTRAINT recruit_posts_work_mode_chk CHECK (work_mode IN ('ONLINE', 'OFFLINE', 'HYBRID')),
    CONSTRAINT recruit_posts_goal_chk CHECK (goal IS NULL OR goal IN ('CONTEST', 'HACKATHON', 'LAUNCH', 'LEARNING')),
    CONSTRAINT recruit_posts_status_chk CHECK (status IN ('OPEN', 'CLOSED')),
    CONSTRAINT recruit_posts_visibility_chk CHECK (visibility IN ('VISIBLE', 'UNDER_REVIEW', 'HIDDEN'))
);

CREATE INDEX recruit_posts_status_sort_at_idx ON recruit_posts (status, sort_at DESC);
CREATE INDEX recruit_posts_status_deadline_idx ON recruit_posts (status, deadline);
CREATE INDEX recruit_posts_work_mode_idx ON recruit_posts (work_mode);
CREATE INDEX recruit_posts_author_id_idx ON recruit_posts (author_id);

CREATE TABLE recruit_roles (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recruit_post_id bigint NOT NULL,
    role varchar(32) NOT NULL,
    headcount integer NOT NULL,
    accepted_count integer NOT NULL DEFAULT 0,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    CONSTRAINT recruit_roles_recruit_post_id_fk FOREIGN KEY (recruit_post_id) REFERENCES recruit_posts (id),
    CONSTRAINT recruit_roles_headcount_chk CHECK (headcount BETWEEN 1 AND 10),
    CONSTRAINT recruit_roles_accepted_count_chk CHECK (accepted_count >= 0 AND accepted_count <= headcount)
);

CREATE INDEX recruit_roles_recruit_post_id_idx ON recruit_roles (recruit_post_id);

CREATE TABLE recruit_post_tags (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recruit_post_id bigint NOT NULL,
    tag_id bigint NOT NULL,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    CONSTRAINT recruit_post_tags_recruit_post_id_fk FOREIGN KEY (recruit_post_id) REFERENCES recruit_posts (id),
    CONSTRAINT recruit_post_tags_tag_id_fk FOREIGN KEY (tag_id) REFERENCES tech_tags (id),
    CONSTRAINT recruit_post_tags_post_tag_uk UNIQUE (recruit_post_id, tag_id)
);

CREATE INDEX recruit_post_tags_tag_id_idx ON recruit_post_tags (tag_id);

CREATE TABLE applications (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recruit_post_id bigint NOT NULL,
    recruit_role_id bigint NOT NULL,
    applicant_id bigint NOT NULL,
    message varchar(300) NOT NULL,
    status varchar(16) NOT NULL,
    attempt integer NOT NULL,
    reject_reason varchar(300),
    expires_at timestamptz NOT NULL,
    decided_by bigint,
    decided_at timestamptz,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    CONSTRAINT applications_recruit_post_id_fk FOREIGN KEY (recruit_post_id) REFERENCES recruit_posts (id),
    CONSTRAINT applications_recruit_role_id_fk FOREIGN KEY (recruit_role_id) REFERENCES recruit_roles (id),
    CONSTRAINT applications_applicant_id_fk FOREIGN KEY (applicant_id) REFERENCES users (id),
    CONSTRAINT applications_decided_by_fk FOREIGN KEY (decided_by) REFERENCES users (id),
    CONSTRAINT applications_status_chk CHECK (status IN ('PENDING', 'ACCEPTED', 'REJECTED', 'EXPIRED', 'CANCELED')),
    CONSTRAINT applications_attempt_chk CHECK (attempt IN (1, 2))
);

CREATE INDEX applications_recruit_post_status_idx ON applications (recruit_post_id, status);
CREATE INDEX applications_applicant_created_at_idx ON applications (applicant_id, created_at DESC);
CREATE INDEX applications_expires_at_idx ON applications (expires_at);
