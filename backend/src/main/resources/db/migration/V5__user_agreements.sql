-- Page 02 onboarding. Consent history for terms, privacy, age 14+, and optional marketing.
CREATE TABLE user_agreements (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL,
    agreement_type varchar(16) NOT NULL,
    version varchar(32) NOT NULL,
    agreed_at timestamptz NOT NULL,
    withdrawn_at timestamptz,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    CONSTRAINT user_agreements_user_id_fk FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT user_agreements_type_chk CHECK (agreement_type IN ('TERMS', 'PRIVACY', 'AGE_14', 'MARKETING')),
    CONSTRAINT user_agreements_user_type_version_uk UNIQUE (user_id, agreement_type, version)
);
