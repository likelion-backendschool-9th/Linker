CREATE TABLE follows (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    follower_id bigint NOT NULL,
    following_id bigint NOT NULL,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    CONSTRAINT follows_follower_id_fk FOREIGN KEY (follower_id) REFERENCES users (id),
    CONSTRAINT follows_following_id_fk FOREIGN KEY (following_id) REFERENCES users (id),
    CONSTRAINT follows_pair_uk UNIQUE (follower_id, following_id),
    CONSTRAINT follows_not_self_chk CHECK (follower_id <> following_id)
);

CREATE INDEX follows_following_id_idx ON follows (following_id, id);
