-- D page 28: subscriptions and payments (ERD 3-9 / 4-9). One-time payment + period end first;
-- trial, billing key and renewal columns exist for later stages but stay unused.
-- Column names user_id, plan, status, current_period_end, grace_until are already read natively
-- by ProMembership, ProSubscriptionLookup, IssueRepositoryImpl and recruiter.AdService.

CREATE TABLE subscriptions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan varchar(16) NOT NULL CHECK (plan IN ('PRO','FLEX','SCOUT')),
    user_id bigint REFERENCES users(id),
    team_id bigint REFERENCES teams(id),
    payer_user_id bigint NOT NULL REFERENCES users(id),
    billing_cycle varchar(16) NOT NULL CHECK (billing_cycle IN ('MONTHLY','YEARLY')),
    status varchar(16) NOT NULL
        CHECK (status IN ('TRIALING','ACTIVE','PAST_DUE','CANCELED','EXPIRED')),
    seats integer CHECK (seats IS NULL OR seats >= 1),
    is_trial boolean NOT NULL DEFAULT false,
    trial_ends_at timestamptz,
    current_period_start timestamptz NOT NULL,
    current_period_end timestamptz NOT NULL,
    cancel_at_period_end boolean NOT NULL DEFAULT false,
    canceled_at timestamptz,
    grace_until timestamptz,
    grace_ends_at timestamptz,
    billing_key_enc text,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    CONSTRAINT subscriptions_target_ck CHECK (
        (plan IN ('PRO','SCOUT') AND user_id IS NOT NULL AND team_id IS NULL AND seats IS NULL)
        OR (plan = 'FLEX' AND team_id IS NOT NULL AND user_id IS NULL AND seats IS NOT NULL)),
    CONSTRAINT subscriptions_scout_no_trial_ck CHECK (plan <> 'SCOUT' OR is_trial = false),
    CONSTRAINT subscriptions_monthly_only_ck CHECK (plan = 'PRO' OR billing_cycle = 'MONTHLY')
);
-- ERD: one live subscription per user/team. EXPIRED and CANCELED rows stay as history.
CREATE UNIQUE INDEX subscriptions_user_live_uk ON subscriptions(user_id)
    WHERE user_id IS NOT NULL AND status IN ('TRIALING','ACTIVE','PAST_DUE');
CREATE UNIQUE INDEX subscriptions_team_live_uk ON subscriptions(team_id)
    WHERE team_id IS NOT NULL AND status IN ('TRIALING','ACTIVE','PAST_DUE');
CREATE INDEX subscriptions_payer_idx ON subscriptions(payer_user_id);
CREATE INDEX subscriptions_period_end_idx ON subscriptions(current_period_end)
    WHERE status IN ('TRIALING','ACTIVE','PAST_DUE');

-- plan, billing_cycle, team_id and seats snapshot the server order at checkout, before any
-- subscription row exists; subscription_id is filled when the server confirm succeeds.
CREATE TABLE payments (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subscription_id bigint REFERENCES subscriptions(id),
    payer_user_id bigint NOT NULL REFERENCES users(id),
    plan varchar(16) NOT NULL CHECK (plan IN ('PRO','FLEX','SCOUT')),
    billing_cycle varchar(16) NOT NULL CHECK (billing_cycle IN ('MONTHLY','YEARLY')),
    team_id bigint REFERENCES teams(id),
    seats integer CHECK (seats IS NULL OR seats >= 1),
    order_id varchar(64) NOT NULL UNIQUE,
    payment_key varchar(200) UNIQUE,
    order_name varchar(100) NOT NULL,
    amount integer NOT NULL CHECK (amount > 0),
    status varchar(24) NOT NULL
        CHECK (status IN ('READY','DONE','CANCELED','PARTIAL_CANCELED','FAILED')),
    method varchar(32),
    approved_at timestamptz,
    canceled_at timestamptz,
    cancel_reason varchar(200),
    refunded_amount integer NOT NULL DEFAULT 0,
    failure_code varchar(64),
    raw_response jsonb,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    CONSTRAINT payments_target_ck CHECK (
        (plan IN ('PRO','SCOUT') AND team_id IS NULL AND seats IS NULL)
        OR (plan = 'FLEX' AND team_id IS NOT NULL AND seats IS NOT NULL)),
    CONSTRAINT payments_done_ck CHECK (status <> 'DONE'
        OR (subscription_id IS NOT NULL AND payment_key IS NOT NULL AND approved_at IS NOT NULL))
);
CREATE INDEX payments_payer_created_idx ON payments(payer_user_id, created_at DESC);
CREATE INDEX payments_subscription_idx ON payments(subscription_id);
