-- Page 04 featured posts. Free 1 / Pro 5. Order is the request order.
CREATE TABLE pinned_posts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL,
    post_id bigint NOT NULL,
    sort_order integer NOT NULL,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    CONSTRAINT pinned_posts_user_id_fk FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT pinned_posts_post_id_fk FOREIGN KEY (post_id) REFERENCES posts (id),
    CONSTRAINT pinned_posts_user_post_uk UNIQUE (user_id, post_id),
    CONSTRAINT pinned_posts_sort_order_chk CHECK (sort_order >= 0)
);

CREATE INDEX pinned_posts_user_order_idx ON pinned_posts (user_id, sort_order, id);
