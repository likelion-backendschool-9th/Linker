-- Team chat mentions. V1–V19 stay as applied; V20 belongs to the team foundation.
-- One row per @person and at most one @all row per message (Policy ch. 8 Mentions).
-- mentioned_user_id is NULL only for the @all row. NULL ids are distinct in UNIQUE, so each
-- rule gets its own partial unique index instead of one composite constraint.

CREATE TABLE chat_message_mentions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message_id bigint NOT NULL,
    mentioned_user_id bigint,
    mention_all boolean NOT NULL,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    CONSTRAINT chat_message_mentions_message_id_fk FOREIGN KEY (message_id) REFERENCES chat_messages (id),
    CONSTRAINT chat_message_mentions_user_id_fk FOREIGN KEY (mentioned_user_id) REFERENCES users (id),
    CONSTRAINT chat_message_mentions_target_chk CHECK (
        (mention_all AND mentioned_user_id IS NULL)
        OR (NOT mention_all AND mentioned_user_id IS NOT NULL)
    )
);

CREATE UNIQUE INDEX chat_message_mentions_user_uk
    ON chat_message_mentions (message_id, mentioned_user_id) WHERE mentioned_user_id IS NOT NULL;
CREATE UNIQUE INDEX chat_message_mentions_all_uk
    ON chat_message_mentions (message_id) WHERE mention_all;
CREATE INDEX chat_message_mentions_user_idx
    ON chat_message_mentions (mentioned_user_id) WHERE mentioned_user_id IS NOT NULL;
