-- C issue cache. Existing ERD tables, promoted from db/issue-schema/*.sql (pages 11–15).
-- V1–V21 stay unchanged. Requires V20 (teams), V12 (github_repos) and users.
-- Columns, checks and indexes match the staged SQL; created_at/updated_at follow ERD "common
-- columns". Defaults stay for set-based native statements (snapshot batch).

CREATE TABLE issues (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id bigint NOT NULL REFERENCES teams (id),
    repo_id bigint NOT NULL REFERENCES github_repos (id),
    github_issue_id bigint NOT NULL UNIQUE,
    github_node_id varchar(255) NOT NULL,
    number integer NOT NULL CHECK (number > 0),
    title text NOT NULL,
    state varchar(16) NOT NULL CHECK (state IN ('OPEN','CLOSED')),
    board_status varchar(32) NOT NULL CHECK (board_status IN ('TODO','IN_PROGRESS','BLOCKED','DONE','OTHER','NONE')),
    project_item_id varchar(255),
    start_date date,
    due_date date,
    author_user_id bigint REFERENCES users (id),
    author_login varchar(255),
    created_via_linker boolean NOT NULL DEFAULT false,
    sync_status varchar(16) NOT NULL DEFAULT 'SYNCED' CHECK (sync_status IN ('SYNCED','PENDING','FAILED')),
    parent_issue_id bigint REFERENCES issues (id),
    sub_issues_total integer NOT NULL DEFAULT 0,
    sub_issues_done integer NOT NULL DEFAULT 0,
    html_url text,
    github_updated_at timestamptz NOT NULL,
    closed_at timestamptz,
    deleted_at timestamptz,
    synced_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (repo_id, number)
);
CREATE INDEX issues_team_due_idx ON issues (team_id, due_date);
CREATE INDEX issues_team_status_idx ON issues (team_id, board_status);
CREATE INDEX issues_team_updated_idx ON issues (team_id, github_updated_at DESC, id DESC);

CREATE TABLE issue_assignees (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    issue_id bigint NOT NULL REFERENCES issues (id) ON DELETE CASCADE,
    github_user_id bigint NOT NULL,
    github_login varchar(255) NOT NULL,
    user_id bigint REFERENCES users (id),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (issue_id, github_user_id)
);
CREATE INDEX issue_assignees_user_idx ON issue_assignees (user_id, issue_id);

CREATE TABLE issue_labels (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    issue_id bigint NOT NULL REFERENCES issues (id) ON DELETE CASCADE,
    name varchar(255) NOT NULL,
    color varchar(16) NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (issue_id, name)
);

CREATE TABLE team_progress_snapshots (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id bigint NOT NULL REFERENCES teams (id),
    snapshot_date date NOT NULL,
    todo_count integer NOT NULL,
    in_progress_count integer NOT NULL,
    blocked_count integer NOT NULL,
    done_count integer NOT NULL,
    overdue_count integer NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (team_id, snapshot_date)
);

-- Pages 12–13. step=CREATE keeps a durable creation intent before GitHub returns an issue.
CREATE TABLE issue_sync_jobs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    issue_id bigint REFERENCES issues (id) ON DELETE CASCADE,
    step varchar(32) NOT NULL CHECK (step IN ('CREATE','ADD_TO_PROJECT','SET_START','SET_DUE','SET_STATUS','CLOSE','REOPEN','SET_ASSIGNEES','SET_LABELS')),
    payload jsonb NOT NULL,
    status varchar(16) NOT NULL CHECK (status IN ('PENDING','RUNNING','DONE','FAILED')),
    attempts integer NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    next_retry_at timestamptz NOT NULL DEFAULT now(),
    last_error text,
    requested_by bigint NOT NULL REFERENCES users (id),
    team_id bigint REFERENCES teams (id),
    request_key uuid,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CHECK (issue_id IS NOT NULL OR (step = 'CREATE' AND team_id IS NOT NULL AND request_key IS NOT NULL))
);
CREATE INDEX issue_sync_jobs_due_idx ON issue_sync_jobs (next_retry_at) WHERE status IN ('PENDING','RUNNING');
CREATE UNIQUE INDEX issue_sync_jobs_active_issue_idx ON issue_sync_jobs (issue_id) WHERE status IN ('PENDING','RUNNING');
CREATE UNIQUE INDEX issue_sync_jobs_create_request_idx ON issue_sync_jobs (requested_by, request_key) WHERE request_key IS NOT NULL;
