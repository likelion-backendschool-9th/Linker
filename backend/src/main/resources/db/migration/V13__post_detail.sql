CREATE TABLE post_likes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id bigint NOT NULL,
    user_id bigint NOT NULL,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    CONSTRAINT post_likes_post_id_fk FOREIGN KEY (post_id) REFERENCES posts (id),
    CONSTRAINT post_likes_user_id_fk FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT post_likes_post_user_uk UNIQUE (post_id, user_id)
);

CREATE INDEX post_likes_user_id_idx ON post_likes (user_id);
CREATE INDEX post_likes_post_id_created_at_idx ON post_likes (post_id, created_at DESC);

CREATE TABLE comments (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id bigint NOT NULL,
    author_id bigint NOT NULL,
    parent_id bigint,
    body varchar(500) NOT NULL,
    visibility varchar(16) NOT NULL,
    edited_at timestamptz,
    deleted_at timestamptz,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    CONSTRAINT comments_post_id_fk FOREIGN KEY (post_id) REFERENCES posts (id),
    CONSTRAINT comments_author_id_fk FOREIGN KEY (author_id) REFERENCES users (id),
    CONSTRAINT comments_parent_id_fk FOREIGN KEY (parent_id) REFERENCES comments (id),
    CONSTRAINT comments_visibility_chk CHECK (visibility IN ('VISIBLE', 'UNDER_REVIEW', 'HIDDEN')),
    CONSTRAINT comments_body_len_chk CHECK (char_length(body) BETWEEN 0 AND 500)
);

CREATE INDEX comments_post_id_created_at_idx ON comments (post_id, created_at ASC);
CREATE INDEX comments_parent_id_idx ON comments (parent_id);
CREATE INDEX comments_author_id_idx ON comments (author_id);

CREATE TABLE post_views (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id bigint NOT NULL,
    viewer_id bigint NOT NULL,
    view_date date NOT NULL,
    source varchar(32) NOT NULL,
    readme_expanded boolean NOT NULL DEFAULT false,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    CONSTRAINT post_views_post_id_fk FOREIGN KEY (post_id) REFERENCES posts (id),
    CONSTRAINT post_views_viewer_id_fk FOREIGN KEY (viewer_id) REFERENCES users (id),
    CONSTRAINT post_views_post_viewer_date_uk UNIQUE (post_id, viewer_id, view_date),
    CONSTRAINT post_views_source_chk CHECK (
        source IN ('FEED', 'PROFILE', 'RECRUIT_POST', 'CHAT_SHARE', 'EXTERNAL')
    )
);

CREATE INDEX post_views_post_id_view_date_idx ON post_views (post_id, view_date DESC);
CREATE INDEX post_views_viewer_id_idx ON post_views (viewer_id);
