-- STEP 0 common foundation.
-- Tables follow ERD page 00 (7-2), plus tech_tags because GET /api/v1/public/tech-tags is a page-00 API.
-- ERD 7-2 lists tech_tags on page 02. This migration creates it once so page 02 must not create it again.
-- github_webhook_deliveries.installation_id has no FK: github_installations is page 08.
-- uploaded_files.purpose is nullable: the current web client sends type IMAGE, which is not an ERD purpose.
-- admins is created without a seed row. There is no operator user yet, and the OTP method is unresolved.

CREATE TABLE users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username varchar(39) NOT NULL,
    display_name varchar(20),
    avatar_url varchar(2048),
    bio varchar(160),
    blog_url varchar(2048),
    email varchar(320),
    email_verified_at timestamptz,
    user_type varchar(32) NOT NULL,
    status varchar(32) NOT NULL,
    suspended_until timestamptz,
    looking_for_team boolean NOT NULL DEFAULT false,
    job_seeking_status varchar(32) NOT NULL DEFAULT 'OFF',
    job_seeking_updated_at timestamptz,
    push_enabled boolean NOT NULL DEFAULT true,
    contribution_synced_at timestamptz,
    last_active_at timestamptz,
    withdraw_requested_at timestamptz,
    deleted_at timestamptz,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    CONSTRAINT users_username_uk UNIQUE (username),
    CONSTRAINT users_user_type_chk CHECK (user_type IN ('DEVELOPER', 'RECRUITER')),
    CONSTRAINT users_status_chk CHECK (status IN ('ACTIVE', 'SUSPENDED', 'WITHDRAWING', 'DELETED')),
    CONSTRAINT users_job_seeking_status_chk CHECK (job_seeking_status IN ('OPEN', 'OFFERS_ONLY', 'OFF'))
);

CREATE INDEX users_status_idx ON users (status);
CREATE INDEX users_looking_for_team_last_active_idx ON users (looking_for_team, last_active_at);
CREATE INDEX users_job_seeking_status_idx ON users (job_seeking_status);

CREATE TABLE auth_identities (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL,
    provider varchar(16) NOT NULL,
    provider_user_id varchar(255) NOT NULL,
    provider_login varchar(255),
    email varchar(320),
    password_hash varchar(255),
    failed_login_count integer NOT NULL DEFAULT 0,
    locked_until timestamptz,
    last_login_at timestamptz,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    CONSTRAINT auth_identities_user_id_fk FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT auth_identities_provider_user_uk UNIQUE (provider, provider_user_id),
    CONSTRAINT auth_identities_provider_chk CHECK (provider IN ('GITHUB', 'EMAIL'))
);

CREATE TABLE github_tokens (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL,
    access_token_enc text NOT NULL,
    access_expires_at timestamptz,
    refresh_token_enc text,
    refresh_expires_at timestamptz,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    CONSTRAINT github_tokens_user_id_fk FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT github_tokens_user_id_uk UNIQUE (user_id)
);

CREATE TABLE user_sessions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL,
    refresh_token_hash varchar(64) NOT NULL,
    user_agent varchar(512),
    ip varchar(64),
    expires_at timestamptz NOT NULL,
    otp_verified_at timestamptz,
    revoked_at timestamptz,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    CONSTRAINT user_sessions_user_id_fk FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT user_sessions_refresh_token_hash_uk UNIQUE (refresh_token_hash)
);

CREATE TABLE admins (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL,
    admin_role varchar(16) NOT NULL,
    otp_secret_enc text,
    otp_enrolled_at timestamptz,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    CONSTRAINT admins_user_id_fk FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT admins_user_id_uk UNIQUE (user_id),
    CONSTRAINT admins_admin_role_chk CHECK (admin_role IN ('OPERATOR', 'LEAD'))
);

CREATE TABLE tech_tags (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(40) NOT NULL,
    category varchar(32) NOT NULL,
    sort_order integer NOT NULL,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    CONSTRAINT tech_tags_name_uk UNIQUE (name)
);

CREATE TABLE uploaded_files (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uploader_id bigint NOT NULL,
    purpose varchar(16),
    storage_key varchar(512) NOT NULL,
    url varchar(2048),
    content_type varchar(127) NOT NULL,
    byte_size bigint NOT NULL,
    width integer,
    height integer,
    original_deleted_at timestamptz,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    CONSTRAINT uploaded_files_uploader_id_fk FOREIGN KEY (uploader_id) REFERENCES users (id),
    CONSTRAINT uploaded_files_storage_key_uk UNIQUE (storage_key),
    CONSTRAINT uploaded_files_purpose_chk CHECK (purpose IS NULL OR purpose IN ('POST', 'CHAT', 'ISSUE', 'AVATAR')),
    CONSTRAINT uploaded_files_byte_size_chk CHECK (byte_size >= 0)
);

CREATE TABLE notifications (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL,
    notification_type varchar(64) NOT NULL,
    actor_id bigint,
    target_type varchar(64),
    target_id bigint,
    link_path varchar(512),
    payload jsonb,
    group_key varchar(128),
    deliver_after timestamptz,
    pushed_at timestamptz,
    read_at timestamptz,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    CONSTRAINT notifications_user_id_fk FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT notifications_actor_id_fk FOREIGN KEY (actor_id) REFERENCES users (id)
);

CREATE TABLE user_blocks (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    blocker_id bigint NOT NULL,
    blocked_id bigint NOT NULL,
    unblocked_at timestamptz,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    CONSTRAINT user_blocks_blocker_id_fk FOREIGN KEY (blocker_id) REFERENCES users (id),
    CONSTRAINT user_blocks_blocked_id_fk FOREIGN KEY (blocked_id) REFERENCES users (id),
    CONSTRAINT user_blocks_not_self_chk CHECK (blocker_id <> blocked_id),
    CONSTRAINT user_blocks_period_chk CHECK (unblocked_at IS NULL OR unblocked_at >= created_at)
);

CREATE UNIQUE INDEX user_blocks_one_active_pair_uk
    ON user_blocks (blocker_id, blocked_id)
    WHERE unblocked_at IS NULL;

CREATE INDEX user_blocks_period_idx
    ON user_blocks (blocker_id, blocked_id, created_at);

CREATE TABLE report_cases (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    target_type varchar(32) NOT NULL,
    target_id bigint NOT NULL,
    target_user_id bigint NOT NULL,
    reporter_count integer NOT NULL,
    status varchar(16) NOT NULL,
    auto_hidden_at timestamptz,
    assigned_admin_id bigint,
    resolved_at timestamptz,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    CONSTRAINT report_cases_target_user_id_fk FOREIGN KEY (target_user_id) REFERENCES users (id),
    CONSTRAINT report_cases_assigned_admin_id_fk FOREIGN KEY (assigned_admin_id) REFERENCES admins (id),
    CONSTRAINT report_cases_target_type_chk CHECK (target_type IN ('USER', 'POST', 'COMMENT', 'RECRUIT_POST', 'TEAM_MESSAGE', 'DM_MESSAGE', 'RECRUITER_AD')),
    CONSTRAINT report_cases_status_chk CHECK (status IN ('PENDING', 'ACTIONED', 'DISMISSED')),
    CONSTRAINT report_cases_reporter_count_chk CHECK (reporter_count >= 0)
);

CREATE UNIQUE INDEX report_cases_pending_target_uk
    ON report_cases (target_type, target_id)
    WHERE status = 'PENDING';

CREATE TABLE reports (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_id bigint NOT NULL,
    reporter_id bigint NOT NULL,
    reason varchar(32) NOT NULL,
    detail varchar(1000),
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    CONSTRAINT reports_case_id_fk FOREIGN KEY (case_id) REFERENCES report_cases (id),
    CONSTRAINT reports_reporter_id_fk FOREIGN KEY (reporter_id) REFERENCES users (id),
    CONSTRAINT reports_case_reporter_uk UNIQUE (case_id, reporter_id),
    CONSTRAINT reports_reason_chk CHECK (reason IN ('SPAM', 'ABUSE', 'SEXUAL', 'PRIVACY', 'PLAGIARISM', 'FAKE_RECRUIT', 'IMPERSONATION', 'ILLEGAL', 'OTHER'))
);

CREATE TABLE github_webhook_deliveries (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    delivery_id varchar(255) NOT NULL,
    event varchar(64) NOT NULL,
    action varchar(128),
    installation_id bigint,
    payload jsonb NOT NULL,
    status varchar(16) NOT NULL,
    attempts integer NOT NULL DEFAULT 0,
    error text,
    processed_at timestamptz,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    CONSTRAINT github_webhook_deliveries_delivery_id_uk UNIQUE (delivery_id),
    CONSTRAINT github_webhook_deliveries_status_chk CHECK (status IN ('RECEIVED', 'PROCESSED', 'FAILED', 'IGNORED'))
);

