-- Page 17 AI chat summary (ERD 3-6). Flex team rooms only; results kept 7 days.
-- jsonb minutes columns stay nullable/unused (reduced API returns summary_line as `summary`).

CREATE TABLE ai_chat_summaries (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id bigint NOT NULL REFERENCES chat_rooms(id),
    requester_id bigint NOT NULL REFERENCES users(id),
    range_type varchar(32) NOT NULL,
    from_message_id bigint,
    to_message_id bigint,
    message_count integer NOT NULL CHECK (message_count >= 0),
    status varchar(16) NOT NULL CHECK (status IN ('PENDING', 'DONE', 'FAILED')),
    summary_line text,
    decisions jsonb,
    action_items jsonb,
    open_questions jsonb,
    llm_model varchar(64),
    shared_message_id bigint REFERENCES chat_messages(id),
    expires_at timestamptz NOT NULL,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL
);

CREATE INDEX ai_chat_summaries_requester_idx ON ai_chat_summaries(requester_id, created_at DESC);
CREATE INDEX ai_chat_summaries_room_idx ON ai_chat_summaries(room_id, created_at DESC);
CREATE INDEX ai_chat_summaries_expires_idx ON ai_chat_summaries(expires_at);
