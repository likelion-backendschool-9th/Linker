-- DIRECT chat image links. V1–V14 stay as applied.
-- Columns follow the ERD: message_id, file_id, sort_order. No payload column.
-- A message cannot repeat a file or a sort position. The same file may be linked from another message.

CREATE TABLE chat_message_images (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message_id bigint NOT NULL,
    file_id bigint NOT NULL,
    sort_order integer NOT NULL,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    CONSTRAINT chat_message_images_message_id_fk FOREIGN KEY (message_id) REFERENCES chat_messages (id),
    CONSTRAINT chat_message_images_file_id_fk FOREIGN KEY (file_id) REFERENCES uploaded_files (id),
    CONSTRAINT chat_message_images_message_file_uk UNIQUE (message_id, file_id),
    CONSTRAINT chat_message_images_message_sort_uk UNIQUE (message_id, sort_order),
    CONSTRAINT chat_message_images_sort_order_chk CHECK (sort_order >= 0 AND sort_order < 10)
);

CREATE INDEX chat_message_images_file_id_idx ON chat_message_images (file_id);
