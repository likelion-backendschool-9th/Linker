ALTER TABLE user_sessions ADD COLUMN operator_seen_at timestamptz;

CREATE TABLE report_message_snapshots (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_id bigint NOT NULL,
    message_id bigint NOT NULL,
    sender_id bigint NOT NULL,
    body text NOT NULL,
    rel_position integer NOT NULL,
    message_created_at timestamptz NOT NULL,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    CONSTRAINT report_message_snapshots_report_id_fk FOREIGN KEY (report_id) REFERENCES reports (id),
    CONSTRAINT report_message_snapshots_rel_position_chk CHECK (rel_position BETWEEN -10 AND 10)
);

CREATE INDEX report_message_snapshots_report_id_idx ON report_message_snapshots (report_id, rel_position);

CREATE TABLE sanctions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL,
    sanction_type varchar(32) NOT NULL,
    reason_code varchar(64),
    reason_detail text,
    starts_at timestamptz NOT NULL,
    ends_at timestamptz,
    case_id bigint,
    admin_id bigint NOT NULL,
    revoked_at timestamptz,
    revoked_by bigint,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    CONSTRAINT sanctions_user_id_fk FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT sanctions_case_id_fk FOREIGN KEY (case_id) REFERENCES report_cases (id),
    CONSTRAINT sanctions_admin_id_fk FOREIGN KEY (admin_id) REFERENCES admins (id),
    CONSTRAINT sanctions_type_chk CHECK (sanction_type IN ('WARNING', 'SUSPENSION', 'PERMANENT_BAN', 'RECRUIT_RESTRICTION', 'REPORT_RESTRICTION'))
);

CREATE INDEX sanctions_user_type_idx ON sanctions (user_id, sanction_type);

CREATE TABLE appeals (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL,
    sanction_id bigint NOT NULL,
    body text NOT NULL,
    status varchar(16) NOT NULL,
    reviewer_admin_id bigint,
    decided_at timestamptz,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    CONSTRAINT appeals_user_id_fk FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT appeals_sanction_id_fk FOREIGN KEY (sanction_id) REFERENCES sanctions (id),
    CONSTRAINT appeals_reviewer_admin_id_fk FOREIGN KEY (reviewer_admin_id) REFERENCES admins (id),
    CONSTRAINT appeals_sanction_id_uk UNIQUE (sanction_id),
    CONSTRAINT appeals_status_chk CHECK (status IN ('PENDING', 'ACCEPTED', 'REJECTED'))
);

CREATE INDEX appeals_status_idx ON appeals (status, id);

CREATE TABLE admin_actions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_id bigint NOT NULL,
    action varchar(32) NOT NULL,
    target_type varchar(32),
    target_id bigint,
    case_id bigint,
    reason text,
    metadata jsonb,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    CONSTRAINT admin_actions_admin_id_fk FOREIGN KEY (admin_id) REFERENCES admins (id),
    CONSTRAINT admin_actions_case_id_fk FOREIGN KEY (case_id) REFERENCES report_cases (id),
    CONSTRAINT admin_actions_action_chk CHECK (action IN (
        'HIDE', 'DELETE', 'RESTORE', 'SANCTION', 'REVOKE', 'DISMISS', 'VIEW_EMAIL', 'APPEAL_ACCEPT', 'APPEAL_REJECT'
    ))
);

CREATE INDEX admin_actions_case_id_idx ON admin_actions (case_id, id);
