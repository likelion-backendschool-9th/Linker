-- Page 24 home feed: seen posts for recommendation exclusion (WBS PostController).
-- 30-day batch cleanup is deferred (daily job later).

CREATE TABLE feed_seen_posts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL,
    post_id bigint NOT NULL,
    seen_at timestamptz NOT NULL,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    CONSTRAINT feed_seen_posts_user_id_fk FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT feed_seen_posts_post_id_fk FOREIGN KEY (post_id) REFERENCES posts (id),
    CONSTRAINT feed_seen_posts_user_post_uk UNIQUE (user_id, post_id)
);

CREATE INDEX feed_seen_posts_user_id_seen_at_idx ON feed_seen_posts (user_id, seen_at DESC);
CREATE INDEX feed_seen_posts_post_id_idx ON feed_seen_posts (post_id);
