-- Page 22 post editor (WBS PostController).
-- github_repos is shared with B (08); created here without installation FK so posts can reference repo_id.
-- team_repos / GitHub sync ownership filtering arrives with B — list APIs may return empty until then.

CREATE TABLE github_repos (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    github_repo_id bigint NOT NULL,
    owner_login varchar(255) NOT NULL,
    name varchar(255) NOT NULL,
    full_name varchar(513) NOT NULL,
    description varchar(1000),
    primary_language varchar(64),
    stargazers_count integer NOT NULL DEFAULT 0,
    forks_count integer NOT NULL DEFAULT 0,
    html_url varchar(2048),
    is_private boolean NOT NULL DEFAULT false,
    is_fork boolean NOT NULL DEFAULT false,
    parent_full_name varchar(513),
    default_branch varchar(255),
    metadata_synced_at timestamptz,
    deleted_at timestamptz,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    CONSTRAINT github_repos_github_repo_id_uk UNIQUE (github_repo_id),
    CONSTRAINT github_repos_full_name_uk UNIQUE (full_name),
    CONSTRAINT github_repos_stargazers_count_chk CHECK (stargazers_count >= 0),
    CONSTRAINT github_repos_forks_count_chk CHECK (forks_count >= 0)
);

CREATE INDEX github_repos_owner_login_idx ON github_repos (owner_login);
CREATE INDEX github_repos_deleted_at_idx ON github_repos (deleted_at);

CREATE TABLE posts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    author_id bigint NOT NULL,
    repo_id bigint NOT NULL,
    team_id bigint,
    summary varchar(60) NOT NULL,
    body varchar(2000) NOT NULL,
    my_role varchar(40),
    period_start date,
    period_end date,
    team_size integer,
    my_commit_count integer NOT NULL DEFAULT 0,
    linker_issue_count integer NOT NULL DEFAULT 0,
    like_count integer NOT NULL DEFAULT 0,
    comment_count integer NOT NULL DEFAULT 0,
    view_count integer NOT NULL DEFAULT 0,
    visibility varchar(16) NOT NULL,
    edited_at timestamptz,
    deleted_at timestamptz,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    CONSTRAINT posts_author_id_fk FOREIGN KEY (author_id) REFERENCES users (id),
    CONSTRAINT posts_repo_id_fk FOREIGN KEY (repo_id) REFERENCES github_repos (id),
    CONSTRAINT posts_visibility_chk CHECK (visibility IN ('VISIBLE', 'UNDER_REVIEW', 'HIDDEN')),
    CONSTRAINT posts_team_size_chk CHECK (team_size IS NULL OR (team_size BETWEEN 1 AND 50)),
    CONSTRAINT posts_summary_len_chk CHECK (char_length(summary) BETWEEN 1 AND 60),
    CONSTRAINT posts_body_len_chk CHECK (char_length(body) <= 2000)
);

-- Soft-deleted posts must not block a later re-post of the same repo (POL-P-1 / 23 delete).
CREATE UNIQUE INDEX posts_author_repo_alive_uk ON posts (author_id, repo_id) WHERE deleted_at IS NULL;
CREATE INDEX posts_author_created_at_idx ON posts (author_id, created_at DESC);
CREATE INDEX posts_created_at_idx ON posts (created_at DESC);
CREATE INDEX posts_repo_id_idx ON posts (repo_id);

CREATE TABLE post_images (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id bigint NOT NULL,
    file_id bigint NOT NULL,
    sort_order integer NOT NULL,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    CONSTRAINT post_images_post_id_fk FOREIGN KEY (post_id) REFERENCES posts (id),
    CONSTRAINT post_images_file_id_fk FOREIGN KEY (file_id) REFERENCES uploaded_files (id),
    CONSTRAINT post_images_post_file_uk UNIQUE (post_id, file_id),
    CONSTRAINT post_images_sort_order_chk CHECK (sort_order >= 0)
);

CREATE INDEX post_images_post_id_idx ON post_images (post_id);

CREATE TABLE post_demo_links (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id bigint NOT NULL,
    url varchar(2048) NOT NULL,
    sort_order integer NOT NULL,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    CONSTRAINT post_demo_links_post_id_fk FOREIGN KEY (post_id) REFERENCES posts (id),
    CONSTRAINT post_demo_links_sort_order_chk CHECK (sort_order >= 0)
);

CREATE INDEX post_demo_links_post_id_idx ON post_demo_links (post_id);

CREATE TABLE post_tags (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id bigint NOT NULL,
    tag_id bigint NOT NULL,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    CONSTRAINT post_tags_post_id_fk FOREIGN KEY (post_id) REFERENCES posts (id),
    CONSTRAINT post_tags_tag_id_fk FOREIGN KEY (tag_id) REFERENCES tech_tags (id),
    CONSTRAINT post_tags_post_tag_uk UNIQUE (post_id, tag_id)
);

CREATE INDEX post_tags_tag_id_idx ON post_tags (tag_id);
