-- Mail delivery is SMTP. Dev uses Mailpit. A production relay is not selected here.

ALTER TABLE user_agreements DROP CONSTRAINT user_agreements_type_chk;
ALTER TABLE user_agreements ADD CONSTRAINT user_agreements_type_chk
    CHECK (agreement_type IN ('TERMS', 'PRIVACY', 'AGE_14', 'AGE_19', 'BUSINESS_TERMS', 'MARKETING'));

CREATE TABLE recruiter_profiles (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL,
    company_name varchar(40) NOT NULL,
    company_email_domain varchar(255) NOT NULL,
    job_title varchar(30) NOT NULL,
    company_url varchar(2048),
    email_verified_at timestamptz NOT NULL,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    CONSTRAINT recruiter_profiles_user_id_fk FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT recruiter_profiles_user_id_uk UNIQUE (user_id)
);

CREATE TABLE email_verifications (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email varchar(320) NOT NULL,
    purpose varchar(32) NOT NULL,
    user_id bigint,
    code_hash varchar(64) NOT NULL,
    attempt_count integer NOT NULL DEFAULT 0,
    expires_at timestamptz NOT NULL,
    used_at timestamptz,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    CONSTRAINT email_verifications_user_id_fk FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT email_verifications_purpose_chk CHECK (purpose IN ('SIGNUP', 'PASSWORD_RESET')),
    CONSTRAINT email_verifications_attempt_count_chk CHECK (attempt_count >= 0)
);

CREATE INDEX email_verifications_open_email_idx
    ON email_verifications (email, purpose, id DESC)
    WHERE used_at IS NULL;
