-- Page 16 chat list. V1 is unchanged.
-- team_id has no FK: the teams table is page 08 and is not created here.
-- payload, client_message_id and edited_at stay off chat_messages until page 17 send.
-- last_message_id and last_read_message_id reference chat_messages, but the FK does not
-- prove the message belongs to the same room. Page 17 must check that when it writes them.
-- This migration does not fill last_message_id. The list computes the visible message instead.

CREATE TABLE chat_rooms (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_type varchar(16) NOT NULL,
    team_id bigint,
    dm_key varchar(64),
    dm_status varchar(16),
    request_kind varchar(16),
    requester_id bigint,
    request_expires_at timestamptz,
    responded_at timestamptz,
    last_message_id bigint,
    last_message_at timestamptz,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    CONSTRAINT chat_rooms_room_type_chk CHECK (room_type IN ('TEAM', 'DIRECT')),
    CONSTRAINT chat_rooms_dm_status_chk CHECK (dm_status IS NULL OR dm_status IN ('REQUESTED', 'ACCEPTED', 'REJECTED', 'EXPIRED')),
    CONSTRAINT chat_rooms_request_kind_chk CHECK (request_kind IS NULL OR request_kind IN ('GENERAL', 'RECRUITING')),
    CONSTRAINT chat_rooms_requester_id_fk FOREIGN KEY (requester_id) REFERENCES users (id),
    CONSTRAINT chat_rooms_direct_chk CHECK (
        room_type <> 'DIRECT'
        OR (dm_key IS NOT NULL AND dm_status IS NOT NULL AND requester_id IS NOT NULL)
    ),
    CONSTRAINT chat_rooms_requested_expiry_chk CHECK (
        dm_status IS DISTINCT FROM 'REQUESTED' OR request_expires_at IS NOT NULL
    )
);

CREATE UNIQUE INDEX chat_rooms_dm_key_uk ON chat_rooms (dm_key) WHERE dm_key IS NOT NULL;
CREATE UNIQUE INDEX chat_rooms_team_id_uk ON chat_rooms (team_id) WHERE room_type = 'TEAM' AND team_id IS NOT NULL;
CREATE INDEX chat_rooms_requester_kind_idx ON chat_rooms (requester_id, request_kind, created_at DESC);

CREATE TABLE chat_room_members (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id bigint NOT NULL,
    user_id bigint NOT NULL,
    last_read_message_id bigint,
    muted boolean NOT NULL DEFAULT false,
    joined_at timestamptz NOT NULL,
    left_at timestamptz,
    hidden_at timestamptz,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    CONSTRAINT chat_room_members_room_id_fk FOREIGN KEY (room_id) REFERENCES chat_rooms (id),
    CONSTRAINT chat_room_members_user_id_fk FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT chat_room_members_room_user_uk UNIQUE (room_id, user_id)
);

CREATE INDEX chat_room_members_active_user_idx ON chat_room_members (user_id) WHERE left_at IS NULL;

CREATE TABLE chat_messages (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id bigint NOT NULL,
    sender_id bigint,
    message_type varchar(16) NOT NULL,
    body text,
    visibility varchar(16) NOT NULL,
    deleted_at timestamptz,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    CONSTRAINT chat_messages_room_id_fk FOREIGN KEY (room_id) REFERENCES chat_rooms (id),
    CONSTRAINT chat_messages_sender_id_fk FOREIGN KEY (sender_id) REFERENCES users (id),
    CONSTRAINT chat_messages_message_type_chk CHECK (
        message_type IN ('TEXT', 'IMAGE', 'ISSUE_CARD', 'PR_EVENT', 'SYSTEM', 'AI_SUMMARY', 'SHARE_CARD')
    ),
    CONSTRAINT chat_messages_visibility_chk CHECK (visibility IN ('VISIBLE', 'HIDDEN'))
);

CREATE INDEX chat_messages_room_id_idx ON chat_messages (room_id, id DESC);

ALTER TABLE chat_rooms
    ADD CONSTRAINT chat_rooms_last_message_id_fk FOREIGN KEY (last_message_id) REFERENCES chat_messages (id);

ALTER TABLE chat_room_members
    ADD CONSTRAINT chat_room_members_last_read_message_id_fk FOREIGN KEY (last_read_message_id) REFERENCES chat_messages (id);
