-- Page 02 profile step. user_tech_tags is the ERD tech stack (max 5).
-- onboarded_at is the screen-routing flag for the session onb claim.
ALTER TABLE users ADD COLUMN onboarded_at timestamptz;

CREATE TABLE user_tech_tags (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL,
    tag_id bigint NOT NULL,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    CONSTRAINT user_tech_tags_user_id_fk FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT user_tech_tags_tag_id_fk FOREIGN KEY (tag_id) REFERENCES tech_tags (id),
    CONSTRAINT user_tech_tags_user_tag_uk UNIQUE (user_id, tag_id)
);
