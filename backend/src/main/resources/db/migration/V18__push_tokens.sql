-- Android Expo push tokens. Sending and invalid-token cleanup stay later workers.

CREATE TABLE push_tokens (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL,
    expo_push_token varchar(512) NOT NULL,
    platform varchar(16) NOT NULL,
    app_version varchar(64),
    last_used_at timestamptz NOT NULL,
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    CONSTRAINT push_tokens_user_id_fk FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT push_tokens_expo_push_token_uk UNIQUE (expo_push_token),
    CONSTRAINT push_tokens_platform_chk CHECK (platform IN ('ANDROID'))
);

CREATE INDEX push_tokens_user_id_idx ON push_tokens (user_id);
