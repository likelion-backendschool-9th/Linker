CREATE TABLE team_ownership_transfers (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id bigint NOT NULL REFERENCES teams(id),
    from_user_id bigint NOT NULL REFERENCES users(id),
    to_user_id bigint NOT NULL REFERENCES users(id),
    status varchar(16) NOT NULL CHECK(status IN ('PENDING','ACCEPTED','DECLINED','CANCELED')),
    responded_at timestamptz,
    created_at timestamptz NOT NULL, updated_at timestamptz NOT NULL
);
CREATE TABLE team_completions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id bigint NOT NULL REFERENCES teams(id),
    completed_by bigint NOT NULL REFERENCES users(id),
    completed_at timestamptz NOT NULL, revertible_until timestamptz NOT NULL,
    confirmed_at timestamptz, reverted_at timestamptz,
    created_at timestamptz NOT NULL, updated_at timestamptz NOT NULL
);
CREATE TABLE completion_records (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    completion_id bigint NOT NULL REFERENCES team_completions(id),
    user_id bigint NOT NULL REFERENCES users(id),
    result varchar(16) NOT NULL CHECK(result IN ('COMPLETED','DROPPED')),
    assigned_issue_count integer NOT NULL,
    done_issue_count integer NOT NULL,
    created_at timestamptz NOT NULL, updated_at timestamptz NOT NULL
);
