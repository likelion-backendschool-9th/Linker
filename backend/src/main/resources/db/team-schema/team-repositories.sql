CREATE TABLE team_repos (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id bigint NOT NULL REFERENCES teams(id),
    repo_id bigint NOT NULL REFERENCES github_repos(id),
    connected_by bigint NOT NULL REFERENCES users(id),
    created_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    CONSTRAINT team_repos_team_repo_uk UNIQUE (team_id, repo_id)
);
CREATE INDEX team_repos_repo_idx ON team_repos(repo_id);
