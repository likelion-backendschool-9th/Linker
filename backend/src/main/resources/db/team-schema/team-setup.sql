CREATE TABLE team_project_boards (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id bigint NOT NULL UNIQUE REFERENCES teams(id),
    github_project_node_id varchar(255) NOT NULL,
    project_number integer NOT NULL,
    title varchar(255) NOT NULL,
    created_by_linker boolean NOT NULL,
    status_field_id varchar(255) NOT NULL,
    start_date_field_id varchar(255) NOT NULL,
    due_date_field_id varchar(255) NOT NULL,
    connected_by bigint NOT NULL REFERENCES users(id),
    created_at timestamptz NOT NULL, updated_at timestamptz NOT NULL
);
CREATE TABLE board_status_mappings (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    board_id bigint NOT NULL REFERENCES team_project_boards(id),
    github_option_id varchar(255) NOT NULL,
    github_option_name varchar(255) NOT NULL,
    linker_status varchar(32) NOT NULL CHECK (linker_status IN ('TODO','IN_PROGRESS','BLOCKED','DONE','OTHER')),
    created_at timestamptz NOT NULL, updated_at timestamptz NOT NULL,
    UNIQUE(board_id,github_option_id)
);
CREATE TABLE pull_requests (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id bigint NOT NULL REFERENCES teams(id), repo_id bigint NOT NULL REFERENCES github_repos(id),
    github_pr_id bigint NOT NULL UNIQUE, number integer NOT NULL,
    title text NOT NULL, state varchar(16) NOT NULL CHECK (state IN ('OPEN','CLOSED','MERGED')),
    draft boolean NOT NULL, author_login varchar(255), html_url varchar(2048),
    merged_at timestamptz, closed_at timestamptz, github_updated_at timestamptz NOT NULL,
    created_at timestamptz NOT NULL, updated_at timestamptz NOT NULL,
    UNIQUE(repo_id,number)
);
