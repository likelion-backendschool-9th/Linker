CREATE TABLE issue_sync_jobs (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 issue_id bigint NOT NULL REFERENCES issues(id) ON DELETE CASCADE,
 step varchar(32) NOT NULL CHECK(step IN ('ADD_TO_PROJECT','SET_START','SET_DUE','SET_STATUS','CLOSE','REOPEN','SET_ASSIGNEES','SET_LABELS')),
 payload jsonb NOT NULL,
 status varchar(16) NOT NULL CHECK(status IN ('PENDING','RUNNING','DONE','FAILED')),
 attempts integer NOT NULL DEFAULT 0 CHECK(attempts>=0),
 next_retry_at timestamptz NOT NULL DEFAULT now(), last_error text,
 requested_by bigint NOT NULL REFERENCES users(id)
);
CREATE INDEX issue_sync_jobs_due_idx ON issue_sync_jobs(next_retry_at) WHERE status IN ('PENDING','RUNNING');
CREATE UNIQUE INDEX issue_sync_jobs_active_issue_idx ON issue_sync_jobs(issue_id) WHERE status IN ('PENDING','RUNNING');
