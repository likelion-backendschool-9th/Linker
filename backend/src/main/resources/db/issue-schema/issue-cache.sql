-- Preconditions: teams, github_repos, users (ERD). Never create copies of B's tables here.
CREATE TABLE issues (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 team_id bigint NOT NULL REFERENCES teams(id), repo_id bigint NOT NULL REFERENCES github_repos(id),
 github_issue_id bigint NOT NULL UNIQUE, github_node_id varchar(255) NOT NULL,
 number integer NOT NULL CHECK(number > 0), title text NOT NULL,
 state varchar(16) NOT NULL CHECK(state IN ('OPEN','CLOSED')),
 board_status varchar(32) NOT NULL CHECK(board_status IN ('TODO','IN_PROGRESS','BLOCKED','DONE','OTHER','NONE')),
 project_item_id varchar(255), start_date date, due_date date,
 author_user_id bigint REFERENCES users(id), author_login varchar(255),
 created_via_linker boolean NOT NULL DEFAULT false,
 sync_status varchar(16) NOT NULL DEFAULT 'SYNCED' CHECK(sync_status IN ('SYNCED','PENDING','FAILED')),
 parent_issue_id bigint REFERENCES issues(id), sub_issues_total integer NOT NULL DEFAULT 0,
 sub_issues_done integer NOT NULL DEFAULT 0, html_url text,
 github_updated_at timestamptz NOT NULL, closed_at timestamptz, deleted_at timestamptz, synced_at timestamptz,
 created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(repo_id,number)
);
CREATE INDEX issues_team_due_idx ON issues(team_id,due_date);
CREATE INDEX issues_team_status_idx ON issues(team_id,board_status);
CREATE INDEX issues_team_updated_idx ON issues(team_id,github_updated_at DESC,id DESC);
CREATE TABLE issue_assignees (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 issue_id bigint NOT NULL REFERENCES issues(id) ON DELETE CASCADE,
 github_user_id bigint NOT NULL, github_login varchar(255) NOT NULL,
 user_id bigint REFERENCES users(id), UNIQUE(issue_id,github_user_id)
);
CREATE INDEX issue_assignees_user_idx ON issue_assignees(user_id,issue_id);
CREATE TABLE issue_labels (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 issue_id bigint NOT NULL REFERENCES issues(id) ON DELETE CASCADE,
 name varchar(255) NOT NULL, color varchar(16) NOT NULL, UNIQUE(issue_id,name)
);
CREATE TABLE team_progress_snapshots (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 team_id bigint NOT NULL REFERENCES teams(id), snapshot_date date NOT NULL,
 todo_count integer NOT NULL, in_progress_count integer NOT NULL,
 blocked_count integer NOT NULL, done_count integer NOT NULL, overdue_count integer NOT NULL,
 UNIQUE(team_id,snapshot_date)
);
